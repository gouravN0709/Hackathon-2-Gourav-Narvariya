#!/usr/bin/env tsx
/**
 * Emits supabase/seed-demo.sql — a deterministic demo account (alex@fitai.app /
 * password123) holding the exact sample week the E2E plan expects. Run:
 *   npm run db:seed-demo   (writes the file)
 *   npm run db:reset && npm run db:apply-demo  (resets and applies it)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

process.env.NEXT_PUBLIC_TODAY = process.env.NEXT_PUBLIC_TODAY ?? '2026-10-15';

async function main(): Promise<void> {
  const { seed } = await import('../src/lib/data/seed');
  const { WORKOUTS } = await import('../src/lib/data/workouts');
  const { TODAY } = await import('../src/lib/date');
  const demo = seed();

  const DEMO_UID = '00000000-0000-4000-8000-000000000001';
  const DEMO_EMAIL = 'alex@fitai.app';
  const DEMO_PASSWORD = 'password123';

  const q = (v: unknown): string => {
    if (v == null) return 'null';
    if (typeof v === 'boolean') return v ? 'true' : 'false';
    if (typeof v === 'number') return `${v}`;
    if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
    return `'${String(v).replace(/'/g, "''")}'`;
  };

  const lines: string[] = [];
  lines.push('-- Generated by scripts/gen-demo-seed.ts — do not edit by hand.');
  lines.push(`BEGIN;`);

  // fresh load: remove an earlier copy of the account (cascades to all rows)
  lines.push(`delete from auth.users where id = '${DEMO_UID}';`);

  lines.push(
    `insert into auth.users (id, aud, role, email, encrypted_password, email_confirmed_at,
      raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token,
      email_change_token_new, email_change, reauthentication_token, is_super_admin)
      values ('${DEMO_UID}', 'authenticated', 'authenticated', ${q(DEMO_EMAIL)},
      crypt(${q(DEMO_PASSWORD)}, gen_salt('bf', 8)), now(),
      '{"provider":"email","providers":["email"]}', '{"name":"Alex Morgan"}',
      now(), now(), '', '', '', '', '', null);`,
  );

  // the on_auth_user_created trigger already created a profile row incl. default plan
  lines.push(
    `update profiles set
      name = 'Alex Morgan',
      email = ${q(DEMO_EMAIL)},
      age = ${demo.user.age},
      height_cm = ${demo.user.height},
      goal = ${q(demo.user.goal)},
      experience = ${q(demo.user.exp)},
      diet = ${q(demo.user.diet)},
      start_weight = ${demo.user.startWeight},
      goal_weight = ${demo.user.goalWeight},
      current_weight = ${demo.weights[TODAY]},
      units = 'metric',
      target_kcal = ${demo.user.targets.kcal},
      target_protein = ${demo.user.targets.protein},
      target_carbs = ${demo.user.targets.carbs},
      target_fats = ${demo.user.targets.fats},
      notif_reminders = true,
      notif_weekly = true,
      notif_coach = false,
      onboarding_completed = true,
      settings = ${q({ meal: demo.ui.meal, sounds: demo.user.notif.sounds === true, tip_dismissed: false, sidebar_collapsed: false })},
      updated_at = now()
      where id = '${DEMO_UID}';`,
  );

  /* weights */
  lines.push(`insert into weight_logs (user_id, logged_on, kg) values`);
  const weightRows = Object.entries(demo.weights).sort(([a], [b]) => (a < b ? -1 : 1));
  lines.push(weightRows.map(([d, kg]) => `  ('${DEMO_UID}', ${q(d)}, ${kg})`).join(',\n') + ';');

  /* sessions + per-set rows (lift lineage matches the store's demo reset exactly) */
  const liftLineage = (lift: string, date: string): number | null => {
    const rec = demo.lifts[lift as keyof typeof demo.lifts];
    if (!rec) return null;
    const keys = Object.keys(rec).filter((k) => k <= date).sort();
    return keys.length ? rec[keys[keys.length - 1]] : null;
  };

  const sessionIds: string[] = [];
  const setRows: string[] = [];
  demo.sessions.forEach((s, si) => {
    const sid = `00000000-0000-4000-8000-${`1000000000${String(si + 1).padStart(2, '0')}`.slice(-12)}`;
    sessionIds.push(sid);
    const workout = WORKOUTS[s.key];
    workout.exercises.forEach((e) => {
      const top = e.lift ? liftLineage(e.lift, s.date) : null;
      for (let i = 1; i <= e.sets; i++) {
        setRows.push(
          `  ('${sid}', '${DEMO_UID}', ${q(e.id)}, ${i}, ${top ?? e.kg}, ${e.reps}, true)`,
        );
      }
    });
  });

  lines.push(`insert into workout_sessions (id, user_id, performed_on, workout_key, name, minutes, volume_kg) values`);
  lines.push(
    demo.sessions
      .map((s, i) => `  ('${sessionIds[i]}', '${DEMO_UID}', ${q(s.date)}, ${q(s.key)}, ${q(WORKOUTS[s.key].name)}, ${s.minutes}, ${s.volume})`)
      .join(',\n') + ';',
  );
  lines.push(`insert into session_sets (session_id, user_id, exercise_key, set_no, kg, reps, done) values`);
  lines.push(setRows.join(',\n') + ';');

  /* today's meal log + 29 days of imported history aggregates */
  const mealRows: string[] = [];
  (Object.keys(demo.meals) as (keyof typeof demo.meals)[]).forEach((meal) => {
    demo.meals[meal].forEach((entry) => {
      mealRows.push(
        `  ('${DEMO_UID}', ${q(TODAY)}, ${q(meal)}, ${q(entry.name)}, ${q(entry.serving)}, 1, ${entry.k}, ${entry.p}, ${entry.c}, ${entry.f}, null)`,
      );
    });
  });
  Object.entries(demo.nutritionHistory).forEach(([day, h]) => {
    mealRows.push(
      `  ('${DEMO_UID}', ${q(day)}, 'snacks', 'Imported history', 'day', 1, ${h.k}, ${h.p}, 0, 0, null)`,
    );
  });
  lines.push(`insert into meal_entries (user_id, logged_on, meal, name, serving_label, servings, kcal, protein, carbs, fats, food_key) values`);
  lines.push(mealRows.join(',\n') + ';');

  /* nova transcript (created_at ordering matches the seed order) */
  const baseTs = new Date('2026-10-15T06:30:00Z').getTime();
  lines.push(`insert into chat_messages (user_id, role, text, card, created_at) values`);
  lines.push(
    demo.chat
      .map((c, i) => `  ('${DEMO_UID}', ${q(c.ai ? 'ai' : 'user')}, ${q(c.text)}, ${Boolean(c.card)}, ${q(new Date(baseTs + i * 60_000).toISOString())})`)
      .join(',\n') + ';',
  );

  lines.push(`COMMIT;`);
  lines.push('');

  const here = path.dirname(fileURLToPath(import.meta.url));
  const outPath = path.resolve(here, '..', 'supabase', 'seed-demo.sql');
  writeFileSync(outPath, lines.join('\n'), 'utf8');
  console.log(`Wrote ${outPath} (${lines.length} lines)`);
}

void main();
